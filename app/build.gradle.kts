// Release signing is optional. The release workflow passes these in when the
// repository has the KEYSTORE_* secrets; otherwise the build falls back to the
// debug key so that a first release always works.
val releaseKeystore: File? = System.getenv("KEYSTORE_PATH")
    ?.takeIf { it.isNotBlank() }
    ?.let { File(it) }
    ?.takeIf { it.exists() }

android {
